// Regenerates Sources/SprintQACore/Theme/Tokens.swift from tokens.json.
// Run from the repo root: swift scripts/generate-tokens.swift
import Foundation

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let data = try Data(contentsOf: root.appendingPathComponent("tokens.json"))
let json = try JSONDecoder().decode([String: [String: String]].self, from: data)

func literal(_ name: String) -> String {
    let theme = json[name]!
    let rows = theme.keys.sorted().map { "        \"\($0)\": \"\(theme[$0]!)\"," }
    return "[\n" + rows.joined(separator: "\n") + "\n    ]"
}

let out = """
// Generated by scripts/generate-tokens.swift from tokens.json. Do not edit.
// tokens.json is Sprint's app/globals.css as bare HSL triples; Sprint's
// tests/surface-tokens.test.ts holds it to the web values.

public enum Tokens {
    public static let light: [String: String] = \(literal("light"))

    public static let dark: [String: String] = \(literal("dark"))
}

"""
try out.write(to: root.appendingPathComponent("Sources/SprintQACore/Theme/Tokens.swift"), atomically: true, encoding: .utf8)
